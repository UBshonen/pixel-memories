/** 플레이어가 처음 서 있을 칸 (광장 한가운데) */
export const SPAWN_TILE = { x: 15, y: 26 };

const CHAR_TO_TILE: Record<string, number> = {
  ".": TILE.GRASS,
  ",": TILE.FLOWER,
  "#": TILE.PATH,
  "~": TILE.WATER,
  T: TILE.TREE,
  "=": TILE.FENCE,
};

/**
 * 글자 그림을 Phaser가 이해하는 숫자 배열로 바꾼다.
 *
 * "TT..." → [4, 4, 0, 0, 0, ...]
 */
export function parseMapArt(art: string[] = MAP_ART): number[][] {
  const width = art[0].length;

  return art.map((row, y) => {
    if (row.length !== width) {
      throw new Error(
        `맵 ${y}번째 줄의 길이가 ${row.length}입니다. 모든 줄은 ${width}칸이어야 합니다.`,
      );
    }

    return [...row].map((char, x) => {
      const tile = CHAR_TO_TILE[char];

      if (tile === undefined) {
        throw new Error(`맵 (${x}, ${y})에 알 수 없는 글자 '${char}'가 있습니다.`);
      }

      return tile;
    });
  });
}
